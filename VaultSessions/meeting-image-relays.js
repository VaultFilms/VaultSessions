'use strict';
(() => {
  const canSend=id=>(typeof speechPlayback==='undefined'||!speechPlayback.busy&&!(speechPlayback.enabled&&controller.running))&&meetingActive&&!meetingRestoring&&!viewSwitching&&!summaryBusy&&!connecting.has(id)&&!pendingDepartures.has(id)&&!waitingOnSkippedReply(id)&&!providerExchanges.has(id)&&!imageJobs?.isBusy(id);
  imageRelays=new RoundtableImageRelays.Queue({
    getTarget:id=>targets[id],
    canProcess:()=>(typeof speechPlayback==='undefined'||!speechPlayback.busy&&!(speechPlayback.enabled&&controller.running))&&meetingActive&&!meetingRestoring&&!viewSwitching,
    canSend,
    status:flight=>request({type:'ROUNDTABLE_STATUS',provider:flight.provider,tabId:flight.tabId,requestId:flight.requestId}),
    idle:flight=>request({type:'ROUNDTABLE_IMAGE_IDLE',...flight}),
    send:async(flight,image,source)=>{
      const previous=foregroundTail;let release;foregroundTail=new Promise(resolve=>{release=resolve;});
      await previous;
      try{
        if(!canSend(flight.provider)||!RoundtableImageRelays.same(targets[flight.provider],flight))return {ok:false,retry:true};
        const ready=await request({type:'ROUNDTABLE_IMAGE_IDLE',...flight});
        if(ready.disconnected){imageRelays.forget(flight.provider);return {ok:false,retry:true};}
        if(!ready.idle)return {ok:false,retry:true};
        if(!canSend(flight.provider)||!RoundtableImageRelays.same(targets[flight.provider],flight))return {ok:false,retry:true};
        const ownTab=isSidePanel?(await chrome.tabs.query({active:true,currentWindow:true}))[0]:await chrome.tabs.getCurrent();
        const text=`This image was generated by ${providers[source].name}. Please refer to it in the ongoing discussion. No reply is needed.\nImage reference: ${flight.imageId}.`;
        try{return await request({type:'ROUNDTABLE_SEND',provider:flight.provider,tabId:flight.tabId,conversationUrl:flight.conversationUrl,requestId:flight.requestId,
          text,images:[image],silent:true,imageRelay:true,guardText:VaultI18n.t('inputGuardNotice'),returnTabId:ownTab?.id});}
        catch(error){return {ok:false,uncertain:error.uncertain!==false&&!error.retry,retry:error.retry,error:error.message};}
      }finally{release();}
    },
    onChange:()=>{
      if(!controller.running&&!summaryBusy)for(const id of [...pendingDepartures])if(!imageRelays.isBusy(id)){pendingDepartures.delete(id);leaveProvider(id);}
      renderParticipants();window.dispatchEvent(new Event('roundtable-image-relays-changed'));},
    onError:(flight,error)=>{console.warn('[VaultSessions image relay]',flight.imageId,flight.provider,error.message);providerStatus(flight.provider,'error',VaultI18n.t('imageRelayFailed'));}
  });
  window.addEventListener('pagehide',()=>imageRelays.dispose());
  window.addEventListener('roundtable-park',()=>imageRelays.dispose());
})();
